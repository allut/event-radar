"""Generate committed _generated modules for both stacks from shared/*.json.

Usage:
    python scripts/generate_shared.py

Re-running with unchanged JSON produces byte-identical output (idempotent).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).parent.parent
SHARED = REPO / "shared"
BACKEND_GEN = REPO / "backend" / "app" / "_generated"
FRONTEND_GEN = REPO / "frontend" / "src" / "_generated"

HEADER_PY = "# AUTO-GENERATED by scripts/generate_shared.py — DO NOT EDIT.\n"
HEADER_TS = "// AUTO-GENERATED by scripts/generate_shared.py — DO NOT EDIT.\n"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _load(rel: str) -> dict | list:
    return json.loads((SHARED / rel).read_text(encoding="utf-8"))


def _py_str(s: str) -> str:
    """Repr a string as a Python double-quoted literal."""
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _ts_str(s: str) -> str:
    """Repr a string as a TypeScript single-quoted literal."""
    escaped = s.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


def _py_frozenset(items: list[str]) -> str:
    quoted = ", ".join(_py_str(v) for v in sorted(items))
    return f"frozenset({{{quoted}}})"


def _py_attr_map(d: dict[str, list[str]]) -> str:
    """Emit a dict[str, set[str]] literal with sorted attr values."""
    pairs = ", ".join(
        f"{_py_str(tag)}: {{{', '.join(_py_str(a) for a in sorted(attrs))}}}"
        for tag, attrs in sorted(d.items())
    )
    return "{" + pairs + "}"


def _ts_set(items: list[str]) -> str:
    """Emit a new Set([...]) literal with single-quoted members."""
    quoted = ", ".join(_ts_str(v) for v in items)
    return f"new Set([{quoted}])"


def _ts_str_list(items: list[str]) -> str:
    """Emit a readonly string array literal."""
    quoted = ", ".join(_ts_str(v) for v in items)
    return f"[{quoted}]"


def _py_dict_str(d: dict[str, str], indent: int = 4) -> str:
    pad = " " * indent
    lines = ["{"]
    for k, v in d.items():
        lines.append(f"{pad}{_py_str(k)}: {_py_str(v)},")
    lines.append("}")
    return "\n".join(lines)


def _py_translations(locale_data: dict[str, dict], locales: tuple[str, ...]) -> str:
    """Render the email TRANSLATIONS dict (one entry per locale, dotted keys)."""
    lines = ["TRANSLATIONS: dict[str, dict[str, str]] = {"]
    for locale in locales:
        lines.append(f'    "{locale}": {{')
        for k, v in locale_data[locale]["email"].items():
            lines.append(f"        {_py_str(k)}: {_py_str(v)},")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines)


def _py_str_list(items: list[str]) -> str:
    quoted = ", ".join(_py_str(v) for v in items)
    return f"[{quoted}]"


def _py_calendar(cal: dict, locales: tuple[str, ...]) -> str:
    lines: list[str] = []
    # MONTH_NAMES
    lines.append("MONTH_NAMES: dict[str, list[str]] = {")
    for locale in locales:
        names = cal["month_names"][locale]
        lines.append(f'    "{locale}": {_py_str_list(names)},')
    lines.append("}")
    lines.append("")
    # DAY_NAMES
    lines.append("DAY_NAMES: dict[str, list[str]] = {")
    for locale in locales:
        names = cal["day_names"][locale]
        lines.append(f'    "{locale}": {_py_str_list(names)},')
    lines.append("}")
    return "\n".join(lines)


def _py_personas(personas: list[dict], locales: tuple[str, ...]) -> str:
    lines = ["PERSONAS: list[dict] = ["]
    for p in personas:
        lines.append("    {")
        lines.append(f"        {_py_str('slug')}: {_py_str(p['slug'])},")
        lines.append(f"        {_py_str('emoji')}: {_py_str(p['emoji'])},")
        lines.append(f"        {_py_str('names')}: {{")
        for loc in locales:
            lines.append(f"            {_py_str(loc)}: {_py_str(p['names'][loc])},")
        lines.append("        },")
        lines.append(f"        {_py_str('vibes')}: {{")
        for loc in locales:
            lines.append(f"            {_py_str(loc)}: {_py_str(p['vibes'][loc])},")
        lines.append("        },")
        lines.append("    },")
    lines.append("]")
    return "\n".join(lines)


def _ts_translations(locale_data: dict[str, dict], locales: tuple[str, ...]) -> str:
    lines = [
        f"type Locale = {' | '.join(_ts_str(loc) for loc in locales)};",
        "export const TRANSLATIONS: Record<Locale, Record<string, string>> = {",
    ]
    for locale in locales:
        lines.append(f"  {locale}: {{")
        for k, v in locale_data[locale]["ui"].items():
            lines.append(f"    {_ts_str(k)}: {_ts_str(v)},")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines)


def _ts_persona_translations(
    personas: list[dict], non_default_locales: tuple[str, ...]
) -> str:
    union = " | ".join(_ts_str(loc) for loc in non_default_locales)
    lines = [
        "type PersonaLocale = { name: string; vibe: string };",
        "export const PERSONA_TRANSLATIONS:",
        f"  Record<string, Partial<Record<{union}, PersonaLocale>>> = {{",
    ]
    for p in personas:
        slug = p["slug"]
        lines.append(f"  {_ts_str(slug)}: {{")
        for loc in non_default_locales:
            n = _ts_str(p["names"][loc])
            v = _ts_str(p["vibes"][loc])
            lines.append(f"    {loc}: {{ name: {n}, vibe: {v} }},")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines)


def _ts_personas_en(personas: list[dict], default_locale: str) -> str:
    lines = [
        "export interface PersonaData { slug: string; emoji: string; name: string; vibe: string; }",
        "export const PERSONAS_EN: PersonaData[] = [",
    ]
    for p in personas:
        slug = _ts_str(p["slug"])
        emoji = _ts_str(p["emoji"])
        name = _ts_str(p["names"][default_locale])
        vibe = _ts_str(p["vibes"][default_locale])
        lines.append(f"  {{ slug: {slug}, emoji: {emoji}, name: {name}, vibe: {vibe} }},")
    lines.append("];")
    return "\n".join(lines)


def _ts_locales(cfg: dict) -> str:
    lines = ["export const LOCALES = ["]
    for loc in cfg["locales"]:
        code = _ts_str(loc["code"])
        label = _ts_str(loc["label"])
        lines.append(f"  {{ code: {code}, label: {label} }},")
    lines.append("] as const;")
    return "\n".join(lines)


def _ts_locale_code_map(cfg: dict) -> str:
    pairs = ", ".join(
        f"{_ts_str(k)}: {_ts_str(v)}" for k, v in cfg["locale_code_map"].items()
    )
    return f"export const LOCALE_CODE_MAP: Record<string, string> = {{ {pairs} }};"


# ---------------------------------------------------------------------------
# Writers
# ---------------------------------------------------------------------------


def write_backend_i18n_data(
    locale_data: dict, calendar: dict, personas: list, locales: tuple[str, ...]
) -> str:
    parts = [
        HEADER_PY,
        "from __future__ import annotations\n",
        "",
        _py_translations(locale_data, locales),
        "",
        _py_calendar(calendar, locales),
        "",
        _py_personas(personas, locales),
        "",
    ]
    return "\n".join(parts)


def write_backend_shared_constants(cfg: dict) -> str:
    cats = _py_frozenset(cfg["categories"])
    vibes = _py_frozenset(cfg["vibes"])
    signals = _py_frozenset(cfg["signals"])
    valid_locales = _py_frozenset([loc["code"] for loc in cfg["locales"]])
    locale_code_map_pairs = ", ".join(
        f"{_py_str(k)}: {_py_str(v)}" for k, v in cfg["locale_code_map"].items()
    )
    safe_schemes = _py_frozenset(cfg["safe_url_schemes"])
    san = cfg["html_sanitize"]
    allowed_tags = _py_frozenset(san["allowed_tags"])
    allowed_attrs = _py_attr_map(san["allowed_attrs"])
    parts = [
        HEADER_PY,
        "from __future__ import annotations\n",
        "",
        f"MAGIC_LINK_TTL_MINUTES: int = {cfg['magic_link_ttl_minutes']}",
        f"SESSION_TTL_DAYS: int = {cfg['session_ttl_days']}",
        f"PERSONA_PRIMARY_WEIGHT: float = {cfg['persona_primary_weight']}",
        f"PERSONA_SECONDARY_WEIGHT: float = {cfg['persona_secondary_weight']}",
        f"DEFAULT_USER_LOCALE: str = {_py_str(cfg['default_locale'])}",
        f"DEFAULT_CURRENCY: str = {_py_str(cfg['default_currency'])}",
        f"DEFAULT_USER_CITY: str = {_py_str(cfg['default_city'])}",
        f"VALID_LOCALES: frozenset[str] = {valid_locales}",
        f"LOCALE_CODE_MAP: dict[str, str] = {{{locale_code_map_pairs}}}",
        f"DEFAULT_LOCALE_CODE: str = {_py_str(cfg['default_locale_code'])}",
        f"VALID_SIGNALS: frozenset[str] = {signals}",
        f"VALID_CATEGORIES: frozenset[str] = {cats}",
        f"VALID_VIBES: frozenset[str] = {vibes}",
        # Schemes accepted for ingested event url/image_url — matches frontend SAFE_URL_SCHEMES.
        # Backend urlsplit().scheme returns colon-less names ("http", "https").
        f"SAFE_URL_SCHEMES: frozenset[str] = {safe_schemes}",
        f"HTML_SANITIZE_ALLOWED_TAGS: frozenset[str] = {allowed_tags}",
        f"HTML_SANITIZE_ALLOWED_ATTRS: dict[str, set[str]] = {allowed_attrs}",
        f"BROWSE_PAGE_SIZE: int = {cfg['browse_page_size']}",
        "",
    ]
    return "\n".join(parts)


def write_frontend_i18n_data(
    locale_data: dict,
    personas: list,
    locales: tuple[str, ...],
    non_default_locales: tuple[str, ...],
    default_locale: str,
) -> str:
    parts = [
        HEADER_TS,
        "",
        _ts_translations(locale_data, locales),
        "",
        _ts_persona_translations(personas, non_default_locales),
        "",
        _ts_personas_en(personas, default_locale),
        "",
    ]
    return "\n".join(parts)


def write_frontend_shared_constants(cfg: dict) -> str:
    san = cfg["html_sanitize"]
    # Flatten per-tag attr map to a unique sorted list for DOMPurify's ALLOWED_ATTR.
    all_attrs: list[str] = sorted(
        {attr for attrs in san["allowed_attrs"].values() for attr in attrs}
    )
    parts = [
        HEADER_TS,
        "",
        f"export const MAGIC_LINK_EXPIRY_MINUTES = {cfg['magic_link_ttl_minutes']};",
        f"export const SESSION_TTL_DAYS = {cfg['session_ttl_days']};",
        f"export const PERSONA_PRIMARY_WEIGHT_THRESHOLD = {cfg['persona_primary_weight']};",
        f"export const PERSONA_SECONDARY_WEIGHT = {cfg['persona_secondary_weight']};",
        "",
        _ts_locales(cfg),
        "",
        _ts_locale_code_map(cfg),
        f"export const DEFAULT_LOCALE_CODE = {_ts_str(cfg['default_locale_code'])};",
        "",
        # URL schemes without trailing colon — matches URL.protocol.replace(/:$/, '').
        f"export const SAFE_URL_SCHEMES = {_ts_set(cfg['safe_url_schemes'])};",
        f"export const SANITIZE_ALLOWED_TAGS = {_ts_str_list(san['allowed_tags'])};",
        f"export const SANITIZE_ALLOWED_ATTR = {_ts_str_list(all_attrs)};",
        "",
        # Fixed 12-category / 10-vibe taxonomy — single source of truth for the
        # /explore filter chips (matches backend VALID_CATEGORIES/VALID_VIBES).
        f"export const CATEGORIES = {_ts_str_list(cfg['categories'])};",
        f"export const VIBES = {_ts_str_list(cfg['vibes'])};",
        "",
        f"export const BROWSE_PAGE_SIZE = {cfg['browse_page_size']};",
        "",
    ]
    return "\n".join(parts)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    cfg = _load("app-config.json")
    # Locale codes flow from shared/app-config.json — the single source of truth —
    # so adding a locale there propagates through the generator automatically.
    locales = tuple(loc["code"] for loc in cfg["locales"])
    default_locale = cfg["default_locale"]
    non_default_locales = tuple(c for c in locales if c != default_locale)

    locale_data = {loc: _load(f"i18n/{loc}.json") for loc in locales}
    calendar = _load("calendar.json")
    personas = _load("personas.json")

    BACKEND_GEN.mkdir(parents=True, exist_ok=True)
    FRONTEND_GEN.mkdir(parents=True, exist_ok=True)

    files: list[tuple[Path, str]] = [
        (BACKEND_GEN / "__init__.py", HEADER_PY),
        (BACKEND_GEN / "i18n_data.py", write_backend_i18n_data(locale_data, calendar, personas, locales)),
        (BACKEND_GEN / "shared_constants.py", write_backend_shared_constants(cfg)),
        (FRONTEND_GEN / "i18nData.ts", write_frontend_i18n_data(locale_data, personas, locales, non_default_locales, default_locale)),
        (FRONTEND_GEN / "sharedConstants.ts", write_frontend_shared_constants(cfg)),
    ]

    for path, content in files:
        path.write_text(content, encoding="utf-8")
        try:
            label = path.relative_to(REPO)
        except ValueError:
            label = path
        print(f"  wrote {label}")

    print("done.")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        sys.exit(1)
